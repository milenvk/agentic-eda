"""Publishing an event instance: the one place its type, its ordering key, and its id are derived.

The activator publishes every answer through ``publish_fact``, and so does any publisher
outside an activation: a demo script, an edge adapter, a relay. An event's key is therefore
the same whichever of them publishes it, because it is read from the event's own data. An
event stated in answer to another gets its id from ``derived_id``, for the same reason: the
same cause gives the same id, whoever publishes.
"""

import uuid

from .broker import PARTITION_KEY, EventBroker, WireEvent
from .contracts import EventContract, binding_of, data_of, key_of

# The namespace of every derived id: fixed, so that one cause gives one id in every process.
_DERIVED_IDS = uuid.UUID("5b1f2d4c-8e3a-4f6b-9c7d-2a0e4b6c8d1f")


def derived_id(source: str, cause_id: str, event_type: str, ordinal: int) -> str:
    """The id for ``source``'s fact number ``ordinal`` of ``event_type``, caused by ``cause_id``.

    A name-based UUID (v5): the same cause gives the same id, so an activation run again
    after a redelivery states its facts under the ids of its first run, and a consumer
    deduplicating by id drops the repeats. The source keeps two components answering one
    event apart, and the type keeps a rerun answering in another order on the same ids. It
    is a hash of fixed length, so a chain of any depth carries no history in its ids.
    """
    name = "\n".join((source, cause_id, event_type, str(ordinal)))
    return str(uuid.uuid5(_DERIVED_IDS, name))


async def publish_fact(
    broker: EventBroker,
    source: str,
    fact: EventContract,
    attributes: dict[str, str] | None = None,
    id: str | None = None,
) -> WireEvent:
    """Publish an event instance through the port.

    The type and the key are taken from the event's class, and the data from its fields.
    ``attributes`` holds what only the publisher knows, such as the workflow's
    ``correlationid``; ``id`` is passed where the publisher derives it, and generated by
    the broker where not.
    """
    attributes = dict(attributes or {})
    key = key_of(fact)
    if key is not None:
        attributes[PARTITION_KEY] = key
    return await broker.publish(
        binding_of(fact).type, source, data_of(fact), id=id, attributes=attributes
    )
